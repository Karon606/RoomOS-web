// 호실번호 표시 정본 — 페이지별 로컬 fmtRoomNo 재정의 금지(lib/fmtDate 와 같은 규약).
//
// 규칙은 한 줄이다. **숫자로만 이루어진 호실번호에만 '호'를 붙인다.**
// 제기역점 46실 중 하나는 roomNo 가 '사무실'이다(비거주 계약만 걸린 방). 무조건 '호'를 붙이면
// '사무실호'가 되는데, 그건 방 이름이 아니다. 반대로 '호'를 아예 안 붙이면 '402'가 층·수량과
// 섞여 읽힌다. 숫자 여부로 가르는 이 규칙이 두 경우를 동시에 지킨다.
//
// 왜 정본으로 올렸나 — 같은 한 줄이 13곳에 손으로 복사돼 있었다(2026-08-12 구조 부채 정리).
// 규칙 자체는 열세 벌이 전부 같았지만 **빈 값의 대체 표기만 갈라져 있었고**('—' 6곳, '' 5곳,
// null 1곳, 무처리 1곳), 그 갈림이 자리마다 옳았다. 그래서 규칙은 하나로 모으고 대체 표기만
// 인자로 남긴다 — 표·카드는 '—'(§06 대상 없음), 문장 안에서 조립되는 자리는 ''(붙이지 않음),
// 검색 캡션처럼 조각을 filter(Boolean) 으로 거르는 자리도 ''.
//
// TenantWishRooms 가 이 규칙을 안 거치고 `{roomNo}호` 를 직접 적어 '사무실호'를 낼 수 있었다.
// 손사본이 열셋이면 열넷째가 규칙을 모르고 태어난다 — 그 자리를 없애는 것이 수렴의 목적이다.

/**
 * 호실번호 표시 문자열.
 * @param no    저장된 roomNo. 숫자만이면 '호'를 붙이고, 아니면 그대로 쓴다.
 * @param empty 값이 없을 때의 표기. 기본은 §06 '대상 없음'의 대시.
 */
export function fmtRoomNo(no: string | null | undefined, empty = '—'): string {
  if (!no) return empty
  return /^\d+$/.test(no) ? `${no}호` : no
}

/**
 * 호실 여럿을 문장 안에 세우는 한 줄 — '601호' · '601호·602호' · '601호·602호 외 1건'.
 *
 * 딸린 계약 경고가 두 화면(수정 폼·상태전환 미니폼)에서 같은 말을 해야 해서 여기 둔다.
 * 화면마다 join 을 적으면 한쪽만 구분자가 바뀌거나 한쪽만 길이를 안 끊는다.
 * 셋부터 꼬리를 다는 것은 좁은 폭(320px) 한 줄에 들어가는 한계가 대략 거기여서다.
 *
 * @param max 그대로 나열할 최대 개수. 넘으면 '외 N건'으로 접는다.
 */
export function fmtRoomList(nos: (string | null | undefined)[], max = 2): string {
  const names = nos.map(n => fmtRoomNo(n, '호실 미지정'))
  return names.length <= max ? names.join('·') : `${names.slice(0, max).join('·')} 외 ${names.length - max}건`
}
