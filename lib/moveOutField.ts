// 입주자 수정 폼이 보낼 '퇴실 예정일' 값을 정하는 정본 — 세 갈래를 한 곳에서 가른다.
//
// 이 칸이 왜 어려운가. 서버는 **필드 부재를 '보존'으로 읽는다**(신고 aae0ab38 관행). 그래서
// 폼은 퇴실일 입력이 화면에 없을 때도 값을 명시로 실어 보낸다 — 조건부로 그리면 화면에서
// 지운 값이 DB 에 그대로 남기 때문이다(신고 c4b74c7d).
//
// 그런데 '명시로 보낸다'를 '빈 값을 보낸다'로 굳혀 두면 반대편이 깨진다. 단기가 아닌 계약이
// 퇴실 예정일을 갖고 있을 때, 연락처만 고쳐 저장해도 그 날짜가 지워진다. 실측 2026-08-28 —
// 화면에 퇴실일 칸이 서는 조건은 '퇴실 예정·퇴실 완료'뿐이라, **거주중인데 퇴실일이 있는**
// 계약은 칸도 없이 매 저장마다 날짜를 잃었다.
//
// 그래서 축이 둘이다. **지금 단기인가**와 **원래 단기였는가.**
//   · 단기다 — 단기 칸의 값을 보낸다.
//   · 단기를 껐다(원래는 단기였다) — 빈 값. 단기 해제는 '퇴실일이 필요 없어졌다'는 뜻이다.
//   · 원래부터 일반이다 — 저장된 값을 그대로 돌려보낸다. 이 자리에는 지우려는 뜻이 없다.
//
// 퇴실 예정·퇴실 완료 상태는 화면에 '퇴실일' 필드가 정본으로 서므로 이 함수를 안 부른다.

export function moveOutFieldValue(args: {
  /** 폼에서 지금 켜져 있는 단기 희망 */
  isShortTerm: boolean
  /** 저장돼 있던 단기 희망 — 이번에 껐는지를 이 값으로만 알 수 있다 */
  wasShortTerm: boolean
  /** 폼이 들고 있는 퇴실 예정일 'YYYY-MM-DD'(비었으면 '') */
  formMoveOut: string
}): string {
  const { isShortTerm, wasShortTerm, formMoveOut } = args
  if (isShortTerm) return formMoveOut
  return wasShortTerm ? '' : formMoveOut
}
