// 서류 메일 문안 정본 — 제목·본문을 여기 한 곳에서만 짓는다(신고 44501308 2단계).
//
// 문안을 코드 안에 흩지 않는 이유는 하나다. 이 글은 운영자가 손님에게 하는 말이라 운영자가
// 고칠 수 있어야 하고, 고칠 자리가 여럿이면 어느 것이 실제로 나가는 말인지 알 수 없게 된다.
//
// **제목과 본문 첫 줄은 잠금화면에 떠도 되는 문장이어야 한다.** 메일 제목은 미리보기로 뜨고,
// 첫 줄도 대부분의 메일 앱이 함께 노출한다. 그래서 이름·호실·금액·대상월·생년월일·계좌를
// 제목과 본문에 적지 않는다. 누구의 서류인지는 첨부 파일 이름이 이미 말한다(lib/docShareQueue 정본).
//
// 서류 종류를 본문에 적는 것은 다르다. 무엇이 왔는지 열어 보기 전에 알아야 받는 사람이 빠진 것을
// 되물을 수 있고, 종류 자체는 그 사람의 사실이 아니라 이 봉투의 목록이다. 발급일·금액·대상월은
// 붙이지 않는다 — 붙이는 순간 본문이 다시 개인정보가 된다(도메인 패널 확정).
//
// 문의처는 영업장 전화를 먼저 쓴다. 회신 주소는 보낸 운영자 계정으로 걸어 두지만, 받는 사람이
// 첨부만 보고 전화로 되묻는 것이 실무에 더 가깝다. 전화가 등록돼 있지 않으면 회신을 안내한다.
//
// 지금은 영업장이 문안을 고칠 자리가 없다(문자 템플릿 SmsTemplate 과 다르다). 두 번째 영업장이
// 한 글자도 못 고치는 상태라, 영업장별 템플릿은 별건 오더로 남겨 두었다.

/** 제목 — 영업장 이름만 붙는다. 사람·호실·금액은 들어가지 않는다. */
export function docMailSubject(propertyName: string): string {
  return `[${propertyName}] 서류를 보내 드립니다`
}

/** 본문(평문) — docTitles 는 화면에 선 이름 그대로(lib/docBundle 의 DOC_TYPE_TITLE). */
export function docMailText(
  propertyName: string, docTitles: string[], propertyPhone: string | null,
): string {
  // 번호 뒤에 조사를 붙이지 않는다 — '으로'와 '로'는 앞 글자 받침을 따라가는데 전화번호 끝자리가
  // 그때그때 달라 어느 쪽도 늘 맞지 않는다. 안내 문장은 고정하고 번호는 다음 줄로 내린다.
  const contact = propertyPhone?.trim()
    ? `내용이 다르거나 문의사항이 있으시면 아래 번호로 연락 주세요.\n전화 ${propertyPhone.trim()}`
    : '내용이 다르거나 문의사항이 있으시면 이 메일에 회신해 주세요.'
  return [
    `안녕하세요. ${propertyName}입니다.`,
    '',
    '요청하신 서류를 첨부해 보내 드립니다.',
    '',
    '첨부',
    ...docTitles.map(t => `- ${t}`),
    '',
    contact,
  ].join('\n')
}
