// 코드가 직접 만들어 넣는 수입 카테고리 이름 정본.
// 영업장 설정(Property.incomeCategories)의 자유 목록과 달리 이 값들은 서버가 자동으로 붙이므로,
// 문자열이 코드 여러 곳에 흩어지면 개명할 때 일부만 바뀌어 과거 데이터와 갈라진다.
//
// '보증금 몰취' — 퇴실 시 보증금 중 돌려주지 않기로 확정된 분.
// 2026-08-01 개명(구 '보증금'). ExtraIncome 은 수익 계정인데 이름이 '보증금' 이면 세무 자료에서
// 보증금을 받은 기록(부채)으로 읽힌다는 회계 패널 지적. 기존 데이터도 함께 옮겼다.
export const FORFEIT_CATEGORY = '보증금 몰취'
export const FORFEIT_CATEGORY_LEGACY = '보증금'

// '위약금' — 예약 취소로 몰취한 선납금. 사업자가 사업과 관련해 받는 위약금이라 기타소득이 아니라
// 사업소득 내 잡수입이다(회계 패널 2026-08-01).
export const PENALTY_CATEGORY = '위약금'

// '청소비' — 청소비 수익. 입실 때 별도로 받은 것과, 퇴실 정산에서 보증금 안의 청소비 몫을 쓴 것 둘 다다.
// 어느 쪽이든 약정된 청소 대가를 실제로 받은 것이라 계정이 같다(운영자 정본 2026-08-11).
//   "보증금 5만원에 이미 청소비 2만원이 포함되어 있었고 난 3만원을 돌려준 거야. 즉 정상적인 청소비를
//    받은 거야. 보증금 몰취는 시설물이 파손되거나 했을 때 (잔여) 3만원에서 차감할 때 몰취가 되는 거지."
// 종전에는 퇴실 미반환분을 사유와 무관하게 전부 FORFEIT_CATEGORY 로 찍어, 정상 청소비 수취가
// 세무 자료에서 몰취(손해배상성 잡수입)로 읽혔다. 지금은 recordDepositReturn 이 청소비 몫과 잔여 몫을
// 갈라 각각 만든다(lib/depositComposition 의 splitWithheldDeposit).
//
// 2026-08-02 에는 "받은 경로대로 둔다(입실 수령은 청소비, 보증금 공제는 몰취)" 로 정했었다. 그때 판단의
// 요지는 **계정 등급**("청소비는 용도가 묶인 돈이 아니라 그냥 사업 수입") 이었고, 그건 지금도 유효하다.
// 2026-08-11 운영자 오더가 뒤집은 것은 등급이 아니라 **라벨**이다. 같은 거래(청소 대가 수취)가
// 받은 경로에 따라 몰취로도 불리면 세무 자료에서 손해배상성 잡수입으로 읽힌다.
// 돌려줄 의무가 없는 확정 대가라 받는 순간 수익이다(회계 패널 2026-08-02).
// 종전에는 이 돈을 isDeposit=true 인 수납 record 로 저장해 매출에서 통째로 빠지고, 동시에
// 있지도 않은 보유 보증금으로 잡혔다(단기 2건 40,000원). 두 번 틀린 구조였다.
export const CLEANING_FEE_CATEGORY = '청소비'

// 퇴실 정산이 **이미 받아 둔 보증금**에서 만든 부가수익의 결제수단 표식(recordDepositReturn 생성 규약).
// 새로 들어온 돈이 아니라 보관 중이던 돈의 성격이 바뀐 것이라, 입금 경로와 반드시 구분된다.
export const DEPOSIT_SOURCED_PAY_METHOD = '보유 보증금'

// '입실 때 별도로 받은 청소비' 만 세는 조건 정본.
//
// 왜 필요한가. 퇴실 정산이 보증금 청소비 몫을 CLEANING_FEE_CATEGORY 로 만들기 시작하면서,
// 카테고리만 보고 세는 자리들이 그 몫까지 '입실 때 받았다' 로 읽게 됐다. 그러면
//   · either/or 판정(cleaningFeeDeductible)이 퇴실 직후 뒤집혀, 적용취소 후 재기록 시
//     환불 최대치가 30,000 에서 50,000 으로 벌어진다(같은 2만원을 두 번 돌려주는 경로).
//   · depositComposition 이 청소비 몫을 두 번 세어 보증금 구성이 어긋난다.
// 결제수단이 구조적 판별자다 — 입실 수령은 현금·계좌이체 등이고 보증금 몫은 위 표식이다.
//
// NOT/not 필터는 SQL 3치 논리 때문에 payMethod 가 NULL 인 행까지 떨어뜨린다(생성 SQL 실측 확인).
// 수기로 넣은 청소비는 결제수단이 비어 있을 수 있고 그건 분명히 입실 수령분이라, OR 로 명시한다.
// as const 를 붙이면 OR 이 readonly 튜플이 되어 Prisma where 에 못 들어간다(입력 타입이 가변 배열).
export const CLEANING_FEE_RECEIVED_WHERE: {
  category: string
  OR: ({ payMethod: null } | { payMethod: { not: string } })[]
} = {
  category: CLEANING_FEE_CATEGORY,
  OR: [{ payMethod: null }, { payMethod: { not: DEPOSIT_SOURCED_PAY_METHOD } }],
}
