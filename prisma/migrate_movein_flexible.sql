-- 입주 희망일 조절 가능 여부 (2026-08-11, 운영자 승인).
--
-- 매칭 알림이 "이 방은 8/30에 빈다"와 "이 사람은 8/16에 들어오고 싶다"를 나란히 놓고도
-- 둘이 맞는지 묻지 못했다. 물으려면 한 가지 사실이 더 필요하다 — 그 사람이 며칠 기다릴 수
-- 있는가. 기다릴 수 있으면 후보로 남고(2군), 그 날짜여야 하면 빠진다.
--
-- 세 값이다. true=일정 조절 가능 · false=그 날짜여야 함 · NULL=아직 안 물어봤다.
-- NULL 을 false 로 읽으면 안 된다 — 안 물어본 사람을 "못 기다린다"고 단정해 후보에서
-- 지워 버리기 때문이다. 그래서 컬럼은 NULL 허용이고 기본값도 두지 않는다.
--
-- 기존 행은 전부 NULL 로 시작한다. 백필도 변환도 없고, 값이 없는 계약의 매칭은
-- '미확인' 군으로 들어가 이 칸이 생기기 전과 같이 후보에 남는다.
-- 물리 테이블명은 lease_terms 다(@@map). 컬럼은 @map 이 없어 camelCase 그대로다.
ALTER TABLE "lease_terms" ADD COLUMN IF NOT EXISTS "moveInFlexible" BOOLEAN;
