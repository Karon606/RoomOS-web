--
-- 'YYYY-MM'(KST 달력). 이 종이가 **어느 달의 납부**를 증명하는가이고, 발행일(issuedAt)과 다른 축이다.
-- 8월에 9월분을 선납받아 미리 발급하면 두 값이 갈린다.
--
-- 왜 필요한가. 서류 시트가 '이번 달 발급본이 아닙니다'를 발행일로 판정하고 있었다. 그러면 위
-- 선납 건이 9월에 stale 로 뜨고, 9월 납부 기록도 있어 '이번 달 확인서 작성' 문까지 열려 같은 달
-- 확인서가 두 장 나간다. 귀속월로 판정하면 그 길이 닫힌다.
--
-- 기존 행은 NULL 이다. 백필하지 않는다 — 옛 발급본의 귀속월은 표시 문자열('2026년 6월분')에만
-- 있고 그것은 운영자가 고칠 수 있는 값이라 사실의 근거로 삼을 수 없다. NULL 이면 판정이 종전대로
-- 발행일 폴백이라 화면이 1비트도 안 바뀐다.
